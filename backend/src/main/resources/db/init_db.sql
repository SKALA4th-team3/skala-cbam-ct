DECLARE table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['country', 'supplier', 'part', 'part_supplier', 'product', 'product_export_country', 'product_part', 'mail_receipt', 'attachment', 'submission', 'extraction_field', 'unregistered_part', 'task', 'alert', 'feedback', 'feedback_draft']
    LOOP
        EXECUTE format('CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', table_name, table_name);
    END LOOP;
END $$;

