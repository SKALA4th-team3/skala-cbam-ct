CREATE TABLE attachment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_receipt_id bigint NOT NULL REFERENCES mail_receipt(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    original_filename varchar(500) NOT NULL,
    storage_uri varchar(1000) NOT NULL,
    mime_type varchar(150) NOT NULL,
    size_bytes bigint NOT NULL,
    -- 기존 Attachment 엔티티가 아직 체크섬을 쓰지 않으므로 CBAM-43에서는 nullable로 호환한다.
    checksum_sha256 varchar(64),
    process_status varchar(20) NOT NULL DEFAULT 'PENDING',
    extracted_text_uri varchar(1000),
    failure_reason varchar(50),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_attachment_receipt_checksum UNIQUE (mail_receipt_id, checksum_sha256),
    CONSTRAINT ck_attachment_size CHECK (size_bytes >= 0),
    CONSTRAINT ck_attachment_status CHECK (process_status IN ('PENDING', 'EXTRACTED', 'UNSUPPORTED', 'FAILED'))
);
CREATE INDEX ix_attachment_mail_receipt ON attachment (mail_receipt_id);
CREATE INDEX ix_attachment_process_status ON attachment (process_status);

CREATE TABLE submission (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_receipt_id bigint NOT NULL REFERENCES mail_receipt(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    supplier_id bigint NOT NULL REFERENCES supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    part_supplier_id bigint REFERENCES part_supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    reporting_month date NOT NULL,
    document_type varchar(50),
    document_month date,
    production_quantity_ton numeric(14,3),
    production_country_code varchar(2) REFERENCES country(code) ON DELETE RESTRICT ON UPDATE CASCADE,
    direct_emission_tco2e numeric(14,3),
    indirect_emission_tco2e numeric(14,3),
    default_value_ratio numeric(5,4),
    applied_factor_year smallint,
    applied_benchmark_factor numeric(10,4),
    factor_frozen_at timestamptz,
    status varchar(20) NOT NULL DEFAULT 'REVIEW_PENDING',
    judgement varchar(20),
    eligibility_status varchar(20),
    severity varchar(10),
    submitted_at timestamptz NOT NULL,
    confirmed_by varchar(100),
    confirmed_at timestamptz,
    rejected_by varchar(100),
    rejected_at timestamptz,
    rejection_reason_code varchar(50),
    rejection_reason text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_submission_month CHECK (date_trunc('month', reporting_month)::date = reporting_month AND (document_month IS NULL OR date_trunc('month', document_month)::date = document_month)),
    CONSTRAINT ck_submission_quantities CHECK ((production_quantity_ton IS NULL OR production_quantity_ton >= 0) AND (direct_emission_tco2e IS NULL OR direct_emission_tco2e >= 0) AND (indirect_emission_tco2e IS NULL OR indirect_emission_tco2e >= 0)),
    CONSTRAINT ck_submission_default_ratio CHECK (default_value_ratio IS NULL OR default_value_ratio BETWEEN 0 AND 1),
    CONSTRAINT ck_submission_status CHECK (status IN ('REVIEW_PENDING', 'CONFIRMED', 'REJECTED', 'NOT_SUBMITTED')),
    CONSTRAINT ck_submission_judgement CHECK (judgement IS NULL OR judgement IN ('QUALIFIED', 'UNQUALIFIED')),
    CONSTRAINT ck_submission_eligibility CHECK (eligibility_status IS NULL OR eligibility_status IN ('USABLE', 'NOT_USABLE')),
    CONSTRAINT ck_submission_severity CHECK (severity IS NULL OR severity IN ('HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_submission_confirmed CHECK (status <> 'CONFIRMED' OR (judgement = 'QUALIFIED' AND part_supplier_id IS NOT NULL AND confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL AND factor_frozen_at IS NOT NULL)),
    CONSTRAINT ck_submission_rejected CHECK (status NOT IN ('REJECTED', 'NOT_SUBMITTED') OR (judgement = 'UNQUALIFIED' AND rejected_by IS NOT NULL AND rejected_at IS NOT NULL AND rejection_reason_code IS NOT NULL))
);
CREATE UNIQUE INDEX uk_submission_receipt_part_month ON submission (mail_receipt_id, part_supplier_id, reporting_month) WHERE part_supplier_id IS NOT NULL;
CREATE INDEX ix_submission_supplier_month_status ON submission (supplier_id, reporting_month, status);
CREATE INDEX ix_submission_part_month_status ON submission (part_supplier_id, reporting_month, status);
CREATE INDEX ix_submission_mail_receipt ON submission (mail_receipt_id);
CREATE INDEX ix_submission_judgement_severity ON submission (judgement, severity, submitted_at);

CREATE TABLE extraction_field (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL REFERENCES submission(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    source_attachment_id bigint REFERENCES attachment(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    field_code varchar(100) NOT NULL,
    sequence_number smallint NOT NULL DEFAULT 1,
    value_type varchar(20) NOT NULL,
    normalized_text text,
    normalized_decimal numeric(24,8),
    normalized_date date,
    normalized_country_code varchar(2) REFERENCES country(code) ON DELETE RESTRICT ON UPDATE CASCADE,
    unit varchar(30),
    raw_value text,
    emission_scope varchar(10),
    source_locator varchar(1000),
    conversion_failure_reason varchar(100),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_extraction_field_sequence UNIQUE (submission_id, field_code, sequence_number),
    CONSTRAINT ck_extraction_value_type CHECK (value_type IN ('TEXT', 'DECIMAL', 'DATE', 'COUNTRY_CODE')),
    CONSTRAINT ck_extraction_scope CHECK (emission_scope IS NULL OR emission_scope IN ('DIRECT', 'INDIRECT')),
    CONSTRAINT ck_extraction_failure_empty CHECK (conversion_failure_reason IS NULL OR (normalized_text IS NULL AND normalized_decimal IS NULL AND normalized_date IS NULL AND normalized_country_code IS NULL)),
    CONSTRAINT ck_extraction_normalized_type CHECK (
        conversion_failure_reason IS NOT NULL OR
        (value_type = 'TEXT' AND normalized_text IS NOT NULL AND normalized_decimal IS NULL AND normalized_date IS NULL AND normalized_country_code IS NULL) OR
        (value_type = 'DECIMAL' AND normalized_text IS NULL AND normalized_decimal IS NOT NULL AND normalized_date IS NULL AND normalized_country_code IS NULL) OR
        (value_type = 'DATE' AND normalized_text IS NULL AND normalized_decimal IS NULL AND normalized_date IS NOT NULL AND normalized_country_code IS NULL) OR
        (value_type = 'COUNTRY_CODE' AND normalized_text IS NULL AND normalized_decimal IS NULL AND normalized_date IS NULL AND normalized_country_code IS NOT NULL)
    )
);
CREATE INDEX ix_extraction_source_attachment ON extraction_field (source_attachment_id);
CREATE INDEX ix_extraction_scope ON extraction_field (emission_scope);

