CREATE TABLE task (
    id varchar(50) PRIMARY KEY,
    parent_task_id varchar(50) REFERENCES task(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    mail_receipt_id bigint REFERENCES mail_receipt(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    submission_id bigint REFERENCES submission(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    feedback_id bigint,
    feedback_draft_id bigint,
    type varchar(40) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    resource_type varchar(50),
    resource_ids jsonb,
    progress_total integer NOT NULL DEFAULT 0,
    progress_done integer NOT NULL DEFAULT 0,
    progress_failed integer NOT NULL DEFAULT 0,
    fallback_applied boolean NOT NULL DEFAULT false,
    unregistered_part_count integer NOT NULL DEFAULT 0,
    attempt_number smallint,
    resend_reason varchar(20),
    recipient_email varchar(254),
    external_message_id varchar(255) UNIQUE,
    error_code varchar(50),
    error_message text,
    requested_by varchar(100),
    sent_at timestamptz,
    started_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_task_type CHECK (type IN ('ANALYZE_MAIL_RECEIPT', 'REVALIDATE_SUBMISSION', 'SEND_REMINDER', 'GENERATE_FEEDBACK_DRAFT', 'REGENERATE_FEEDBACK_DRAFT', 'SEND_FEEDBACK')),
    CONSTRAINT ck_task_status CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_task_resend_reason CHECK (resend_reason IS NULL OR resend_reason IN ('SEND_FAILED', 'NO_REPLY')),
    CONSTRAINT ck_task_progress CHECK (progress_total >= 0 AND progress_done >= 0 AND progress_failed >= 0 AND progress_done + progress_failed <= progress_total),
    CONSTRAINT ck_task_completion CHECK ((status = 'COMPLETED' AND completed_at IS NOT NULL) OR (status = 'FAILED' AND error_code IS NOT NULL AND error_message IS NOT NULL AND completed_at IS NOT NULL) OR status IN ('PENDING', 'PROCESSING')),
    CONSTRAINT ck_task_send_fields CHECK (type NOT IN ('SEND_REMINDER', 'SEND_FEEDBACK') OR (feedback_id IS NOT NULL AND feedback_draft_id IS NOT NULL AND attempt_number IS NOT NULL AND recipient_email IS NOT NULL)),
    CONSTRAINT ck_task_attempt CHECK (attempt_number IS NULL OR (attempt_number = 1 AND resend_reason IS NULL) OR (attempt_number >= 2 AND resend_reason IS NOT NULL)),
    CONSTRAINT ck_task_sent CHECK (type NOT IN ('SEND_REMINDER', 'SEND_FEEDBACK') OR status <> 'COMPLETED' OR (external_message_id IS NOT NULL AND sent_at IS NOT NULL))
);
CREATE INDEX ix_task_status_created ON task (status, created_at);
CREATE INDEX ix_task_mail_type_created ON task (mail_receipt_id, type, created_at);
CREATE INDEX ix_task_submission_type_created ON task (submission_id, type, created_at);
CREATE INDEX ix_task_feedback_type_created ON task (feedback_id, type, created_at);
CREATE UNIQUE INDEX uk_task_feedback_attempt ON task (feedback_id, attempt_number) WHERE feedback_id IS NOT NULL AND attempt_number IS NOT NULL;

CREATE TABLE alert (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_supplier_id bigint REFERENCES part_supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    unregistered_part_id bigint REFERENCES unregistered_part(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    submission_id bigint REFERENCES submission(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    reporting_month date NOT NULL,
    rule_id varchar(10) NOT NULL,
    check_id varchar(50) NOT NULL,
    outcome varchar(10) NOT NULL,
    severity varchar(10) NOT NULL,
    observed_value varchar(255),
    reference_value varchar(255),
    message text NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'OPEN',
    validated_at timestamptz NOT NULL,
    resolved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_alert_month CHECK (date_trunc('month', reporting_month)::date = reporting_month),
