CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE country (
    code varchar(2) PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    is_eu_member boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_registration_number varchar(40) NOT NULL,
    name varchar(120) NOT NULL,
    country_code varchar(2) NOT NULL,
    contact_name varchar(60) NOT NULL,
    contact_email varchar(254) NOT NULL,
    contact_phone varchar(30),
    status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    status_reason varchar(500),
    inactive_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_supplier_business_registration_number UNIQUE (business_registration_number),
    CONSTRAINT uk_supplier_contact_email UNIQUE (contact_email),
    CONSTRAINT fk_supplier_country FOREIGN KEY (country_code) REFERENCES country(code) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT ck_supplier_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_supplier_inactive CHECK (status <> 'INACTIVE' OR (status_reason IS NOT NULL AND inactive_at IS NOT NULL))
);
CREATE UNIQUE INDEX uk_supplier_contact_email_lower ON supplier (lower(contact_email));
CREATE INDEX ix_supplier_name ON supplier (name);
CREATE INDEX ix_supplier_country_status ON supplier (country_code, status);

CREATE TABLE part (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_code varchar(40) NOT NULL UNIQUE,
    name varchar(120) NOT NULL UNIQUE,
    cn_code varchar(8) NOT NULL,
    unit varchar(10) NOT NULL,
    benchmark_factor numeric(10,4),
    benchmark_factor_year smallint,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_part_cn_code CHECK (cn_code ~ '^[0-9]{8}$'),
    CONSTRAINT ck_part_unit CHECK (unit IN ('KG', 'TON', 'EA')),
    CONSTRAINT ck_part_benchmark CHECK (benchmark_factor IS NULL OR benchmark_factor >= 0),
    CONSTRAINT ck_part_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_part_cn_code ON part (cn_code);
CREATE INDEX ix_part_status ON part (status);

CREATE TABLE part_supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id bigint NOT NULL REFERENCES part(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    supplier_id bigint NOT NULL REFERENCES supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_part_supplier UNIQUE (part_id, supplier_id),
    CONSTRAINT ck_part_supplier_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE INDEX ix_part_supplier_supplier_status ON part_supplier (supplier_id, status);

CREATE TABLE product (
