CREATE INDEX ix_alert_submission_rule ON alert (submission_id, rule_id, check_id);
CREATE INDEX ix_alert_status_severity_month ON alert (status, severity, reporting_month);

CREATE TABLE feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    part_supplier_id bigint REFERENCES part_supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    submission_id bigint REFERENCES submission(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    confirmed_draft_id bigint,
    reporting_month date NOT NULL,
    type varchar(20) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'DRAFT',
    recipient_email varchar(254),
    confirmed_by varchar(100),
    locked_at timestamptz,
    discarded_by varchar(100),
    discarded_at timestamptz,
    discard_reason text,
    created_by varchar(100),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_feedback_month CHECK (date_trunc('month', reporting_month)::date = reporting_month),
    CONSTRAINT ck_feedback_type CHECK (type IN ('FEEDBACK', 'REMINDER')),
    CONSTRAINT ck_feedback_status CHECK (status IN ('DRAFT', 'READY_TO_SEND', 'SENT', 'DISCARDED')),
    CONSTRAINT ck_feedback_target CHECK ((type = 'FEEDBACK' AND submission_id IS NOT NULL) OR (type = 'REMINDER' AND submission_id IS NULL)),
    CONSTRAINT ck_feedback_ready CHECK (status <> 'READY_TO_SEND' OR (confirmed_draft_id IS NOT NULL AND recipient_email IS NOT NULL AND confirmed_by IS NOT NULL AND locked_at IS NOT NULL)),
    CONSTRAINT ck_feedback_discarded CHECK (status <> 'DISCARDED' OR (discarded_by IS NOT NULL AND discarded_at IS NOT NULL AND discard_reason IS NOT NULL))
);
CREATE INDEX ix_feedback_supplier_month_type ON feedback (supplier_id, reporting_month, type);
CREATE INDEX ix_feedback_part_month ON feedback (part_supplier_id, reporting_month);
CREATE INDEX ix_feedback_submission ON feedback (submission_id);
CREATE INDEX ix_feedback_status_created ON feedback (status, created_at);

CREATE TABLE feedback_draft (
