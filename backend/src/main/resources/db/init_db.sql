CREATE TABLE product_part (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    part_supplier_id bigint NOT NULL REFERENCES part_supplier(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    input_qty_per_ton numeric(10,3) NOT NULL,
